/**
 * Writes public/pricing-config.js from environment variables (Vercel / local .env).
 * Run before `expo export --platform web` so the static pricing page can load Supabase + Paddle.
 *
 * Expected env (any of the listed names):
 * - Supabase URL: EXPO_PUBLIC_SUPABASE_URL or SUPABASE_URL
 * - Supabase anon: EXPO_PUBLIC_SUPABASE_ANON_KEY or SUPABASE_ANON_KEY
 * - Paddle client token (Billing): EXPO_PUBLIC_PADDLE_CLIENT_TOKEN or PADDLE_CLIENT_TOKEN
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(__dirname, '..', 'public', 'pricing-config.js');

const cfg = {
  supabaseUrl: process.env.EXPO_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL || '',
  supabaseAnonKey: process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY || '',
  paddleClientToken:
    process.env.EXPO_PUBLIC_PADDLE_CLIENT_TOKEN || process.env.PADDLE_CLIENT_TOKEN || '',
};

const contents = `// Auto-generated by scripts/inject-pricing-config.mjs — do not edit by hand
window.NAUTICAL_PRICING_CONFIG = ${JSON.stringify(cfg, null, 0)};
`;

fs.writeFileSync(outPath, contents, 'utf8');
console.log('Wrote', outPath);
