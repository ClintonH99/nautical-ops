/**
 * Writes public/pricing-config.js from environment variables (Vercel / local .env).
 * Run before `expo export --platform web` so the static pricing page can load Supabase + Paddle.
 *
 * Expected env (any of the listed names):
 * - Supabase URL: EXPO_PUBLIC_SUPABASE_URL or SUPABASE_URL
 * - Supabase anon: EXPO_PUBLIC_SUPABASE_ANON_KEY or SUPABASE_ANON_KEY
 * - Paddle client token (Billing): EXPO_PUBLIC_PADDLE_CLIENT_TOKEN or PADDLE_CLIENT_TOKEN
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(__dirname, '..', 'public', 'pricing-config.js');

/** Vercel/build env values often have accidental whitespace when pasted in the dashboard. */
function envStr(...keys) {
  for (const key of keys) {
    const raw = process.env[key];
    if (raw == null) continue;
    const v = String(raw).trim();
    if (v !== '') return v;
  }
  return '';
}

const cfg = {
  supabaseUrl: envStr('EXPO_PUBLIC_SUPABASE_URL', 'SUPABASE_URL'),
  supabaseAnonKey: envStr('EXPO_PUBLIC_SUPABASE_ANON_KEY', 'SUPABASE_ANON_KEY'),
  paddleClientToken: envStr('EXPO_PUBLIC_PADDLE_CLIENT_TOKEN', 'PADDLE_CLIENT_TOKEN'),
};

const contents = `// Auto-generated by scripts/inject-pricing-config.mjs — do not edit by hand
window.NAUTICAL_PRICING_CONFIG = ${JSON.stringify(cfg, null, 0)};
`;

fs.writeFileSync(outPath, contents, 'utf8');
console.log(
  'inject-pricing-config:',
  outPath,
  '| supabaseUrl:',
  cfg.supabaseUrl ? 'set' : 'MISSING',
  '| supabaseAnonKey:',
  cfg.supabaseAnonKey ? 'set' : 'MISSING',
  '| paddleClientToken:',
  cfg.paddleClientToken ? 'set' : 'MISSING'
);
